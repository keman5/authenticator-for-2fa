export function t(
  language: string,
  key: MessageKey,
  values?: MessageValues
): string {
  const locale = Object.hasOwn(dictionaries, language)
    ? (language as LanguageCode)
    : 'en';
  return dictionaries[locale][key].replace(
    /\{(\w+)\}/g,
    (slot, name: string) => {
      if (!values || !Object.hasOwn(values, name)) return slot;
      return String(values[name]);
    }
  );
}

export const tr = (key: MessageKey, values?: MessageValues): string =>
  t(authenticatorVault.settings.language, key, values);
